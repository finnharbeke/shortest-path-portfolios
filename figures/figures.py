def calendar_heatmap(csv_path='../data/apr2015.csv', out='apr2015.pdf'):
    """Plot average edge speed as a calendar heatmap: x = day of week, y = week × time of day."""
    df = pd.read_csv(csv_path, parse_dates=['time'])
    speeds = df['avg_speed_kmh'].values  # shape (4320,)

    n_slots = 144  # 24 h × 6 slots/h (10-min intervals)
    n_days = len(speeds) // n_slots  # 30

    # April 1, 2015 = Wednesday → Python weekday 2 (Mon=0)
    start_weekday = 2

    # Build the 2D grid: (num_weeks × 144) rows × 7 columns
    grid = np.full((5 * n_slots, 7), np.nan)

    for i, speed in enumerate(speeds):
        day = i // n_slots
        time_slot = i % n_slots
        dow = (start_weekday + day) % 7  # Mon=0 … Sun=6
        week = (day + start_weekday) // 7
        grid[week * n_slots + time_slot, dow] = speed

    # Labels for time of day (every 6 hours)
    time_labels = ['00:00', '06:00', '12:00', '18:00']
    time_ticks = [h * 6 for h in range(0, 24, 6)]  # 6 slots per hour

    # Labels for weeks
    week_labels = [f'W{i + 1}' for i in range(5)]
    # y-position of each week label: centre of each week block
    week_ticks = [i * n_slots + n_slots // 2 for i in range(5)]

    fig, ax = plt.subplots(figsize=(7, 3.5))

    cmap = plt.get_cmap('flare_r').copy()
    cmap.set_bad('white')

    im = ax.imshow(grid, aspect='auto', cmap=cmap, interpolation='nearest')

    # Grid lines for calendar feel
    for w in range(1, 5):
        ax.axhline(y=w * n_slots - 0.5, color='#444444', linewidth=1, linestyle='-')
    for d in range(1, 7):
        ax.axvline(x=d - 0.5, color='#444444', linewidth=1, linestyle='-')

    # Axes
    ax.set_xticks(range(7))
    ax.set_xticklabels(['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'])

    # Time ticks on the left, with week number prepended on 12:00 labels
    left_ticks = []
    left_labels = []
    for w in range(5):
        offset = w * n_slots
        for tick, lab in zip(time_ticks, time_labels):
            if lab == '00:00':
                continue  # Skip 00:00 in the first week
            left_ticks.append(offset + tick)
            if lab == '12:00':
                left_labels.append(f'Week {w + 1} {lab}')
            else:
                left_labels.append(lab)
    ax.set_yticks(left_ticks)
    ax.set_yticklabels(left_labels, fontsize=8)

    ax.set_xlabel('Day of the week')
    ax.set_ylabel('Week & Time of day')

    # Colour bar, placed to the right of the right-side ticks
    cbar = fig.colorbar(im, ax=ax)
    cbar.set_label('Average edge speed (km/h)')

    ax.set_title('Taxi travel speeds in Shanghai, April 2025')
    fig.tight_layout(pad=.5)
    fig.savefig(out)
    print(f'Saved {out}')
    plt.gcf().clear()


