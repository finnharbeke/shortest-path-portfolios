class _StarOnCircle(mpatches.Patch):
    """Dummy handle: white star on a gray circle."""


class _BlackStar(mpatches.Patch):
    """Dummy handle: solid black circle."""

# deepseek-v4-flash
class StarOnCircleHandler(HandlerPatch):
    """Legend handler: draws a gray circle under a white 5-pointed star."""
    def create_artists(self, legend, orig_handle, xdescent, ydescent,
                       width, height, fontsize, trans):
        cx = width / 2 - xdescent
        cy = height / 2 - ydescent
        r = min(width, height) / 2.2

        circle = mpatches.Circle((cx, cy), r, facecolor='k', edgecolor='none')

        inner_r = (3 - 5 ** 0.5) / 2
        verts = []
        for i in range(11):
            i_mod = i % 10
            rad = r * (1.0 if i_mod % 2 == 0 else inner_r)
            angle = math.pi / 2 + i_mod * math.pi / 5
            verts.append((cx + rad * math.cos(angle), cy + rad * math.sin(angle)))
        star = mpatches.Polygon(verts, facecolor='white', edgecolor='none')

        return [circle, star]


class BlackStarHandler(HandlerPatch):
    """Legend handler: draws a solid black circle."""
    def create_artists(self, legend, orig_handle, xdescent, ydescent,
                       width, height, fontsize, trans):
        cx = width / 2 - xdescent
        cy = height / 2 - ydescent
        r = min(width, height) / 2.2
        inner_r = (3 - 5 ** 0.5) / 2
        verts = []
        for i in range(11):
            i_mod = i % 10
            rad = r * (1.0 if i_mod % 2 == 0 else inner_r)
            angle = math.pi / 2 + i_mod * math.pi / 5
            verts.append((cx + rad * math.cos(angle), cy + rad * math.sin(angle)))
        star = mpatches.Polygon(verts, facecolor='k', edgecolor='none')
        return [star]


